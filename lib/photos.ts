export function getRandomPhoto(seed?: number): string {
  const index = seed !== undefined
    ? Math.abs(seed) % ALL_PHOTOS.length
    : Math.floor(Math.random() * ALL_PHOTOS.length);
  return ALL_PHOTOS[index];
}

export function getRandomPhotos(count: number, seed?: number): string[] {
  const shuffled = [...ALL_PHOTOS];
  let s = seed ?? Math.floor(Math.random() * 10000);
  for (let i = shuffled.length - 1; i > 0; i--) {
    s = (s * 9301 + 49297) % 233280;
    const j = Math.floor((s / 233280) * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, count);
}

